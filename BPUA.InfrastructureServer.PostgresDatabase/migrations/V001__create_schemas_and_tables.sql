CREATE SCHEMA IF NOT EXISTS infrastructure_server;
CREATE SCHEMA IF NOT EXISTS hosted_application_layer;
CREATE SCHEMA IF NOT EXISTS hosted_application_layer_log;

CREATE TABLE public.hosted_application_layer
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    application_layer_name varchar(32) NOT NULL,
    domain_name varchar(128) NOT NULL,
    url varchar(1024) NOT NULL,
    use_case_name varchar(128) NOT NULL,
    business_guid uuid NULL,
    business_string_representation text NULL,
    created_by_user_guid uuid NOT NULL DEFAULT '00000000-0000-0000-0000-000000000001',
    created_by_user_name varchar(50) NOT NULL DEFAULT 'System',
    date_of_creation timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_of_modification timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    guid uuid NOT NULL DEFAULT gen_random_uuid(),
    is_archived boolean NOT NULL DEFAULT false,
    is_deleted boolean NOT NULL DEFAULT false,
    modified_by_user_guid uuid NOT NULL DEFAULT '00000000-0000-0000-0000-000000000001',
    modified_by_user_name varchar(50) NOT NULL DEFAULT 'System',
    string_representation varchar(290)
        GENERATED ALWAYS AS
        (domain_name || '.' || use_case_name || '.' || application_layer_name) STORED,
    CONSTRAINT pk_hosted_application_layer PRIMARY KEY (id),
    CONSTRAINT uc_hosted_application_layer_bpua_identifier
        UNIQUE (domain_name, use_case_name, application_layer_name),
    CONSTRAINT uc_hosted_application_layer_string_representation
        UNIQUE (string_representation)
);

